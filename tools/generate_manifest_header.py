#!/usr/bin/env python3
"""Deterministically generate/check the firmware hardware header."""
import argparse, json, pathlib, sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
MANIFEST=ROOT/'hardware/manifest.json'; OUTPUT=ROOT/'firmware/generated/hardware_manifest.hpp'
GPIO_KEYS=('SCAN_CLK','SCAN_LOAD','BUTTON_DATA1','BUTTON_DATA2','BUTTON_DATA3','BUTTON_DATA4','BUTTON_DATA5','BUTTON_DATA6','BUTTON_DATA7','BUTTON_DATA8','BUTTON_DATA9','ENC_LED_DATA','RGB_DATA_RAW','ENC_LED_LATCH','ENC_LED_BLANK')
def validate(m):
    errors=[]
    if m.get('schema_version')!=1: errors.append('schema_version must be 1')
    for key in GPIO_KEYS:
        if not isinstance(m.get('gpio',{}).get(key),int): errors.append(f'missing integer gpio.{key}')
    if len(set(m.get('gpio',{}).values())) != len(m.get('gpio',{})): errors.append('GPIO assignments overlap')
    expected={'buttons-1x8':8,'buttons-2x5':16,'nav':8,'pads':16,'encoders':24}
    for board,bits in expected.items():
        regs=m.get('board_types',{}).get(board,{}).get('registers',[])
        if len(regs)*8!=bits or any(len(r.get('bits',[]))!=8 for r in regs): errors.append(f'{board} chain must contain {bits} bits')
    if m.get('board_types',{}).get('encoders',{}).get('tlc5947',{}).get('bits_per_frame')!=288: errors.append('TLC frame must be 288 bits')
    if errors: raise ValueError('\n'.join(errors))
def render(m):
    g=m['gpio']; data=[g[f'BUTTON_DATA{i}'] for i in range(1,10)]
    return f'''#pragma once
// GENERATED by tools/generate_manifest_header.py; do not edit.
#include <array>
#include <cstdint>
namespace ng::hw {{
inline constexpr char hardware_baseline[] = "{m['hardware_baseline']}";
inline constexpr uint8_t scan_clk={g['SCAN_CLK']}, scan_load={g['SCAN_LOAD']};
inline constexpr std::array<uint8_t,9> serial_data={{{','.join(map(str,data))}}};
inline constexpr uint8_t enc_led_data={g['ENC_LED_DATA']}, rgb_data={g['RGB_DATA_RAW']}, enc_led_latch={g['ENC_LED_LATCH']}, enc_led_blank={g['ENC_LED_BLANK']};
inline constexpr uint8_t max_scan_clocks=24;
inline constexpr uint16_t tlc_frame_bits=288;
}}
'''
def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--check',action='store_true'); args=ap.parse_args()
    m=json.loads(MANIFEST.read_text()); validate(m); output=render(m)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text()!=output:
            print(f'stale generated file: {OUTPUT}',file=sys.stderr); return 1
        print('generated manifest header: fresh'); return 0
    OUTPUT.write_text(output); print(f'wrote {OUTPUT}'); return 0
if __name__=='__main__': raise SystemExit(main())
